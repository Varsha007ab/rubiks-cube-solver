def sample_grid(frame):
    h, w = frame.shape[:2]

    # Margin used in detect_face for patch extraction
    margin = 8
    # Required minimum effective sticker size for patch extraction
    # (patch itself must be at least 1x1, so sticker_size >= 2*margin + 1)
    MIN_STICKER_SIZE_FOR_PATCH = 2 * margin + 1 # 17

    # Calculate an initial square_size based on the smaller dimension, leaving some margin
    # Aim for the grid (3 squares + 2 gaps) to be about 80% of the min_dim
    # Assuming gap is about 1/5th of a square_size: 3*S + 2*(S/5) = 3.4*S
    # So, S = (0.8 * min_dim) / 3.4
    estimated_square_size = int((min(h, w) * 0.8) / 3.4)

    # Ensure square_size is at least the minimum required for patch extraction
    dynamic_square_size = max(MIN_STICKER_SIZE_FOR_PATCH, estimated_square_size)

    # Recalculate gap based on the actual dynamic_square_size
    dynamic_gap = max(5, int(dynamic_square_size * 0.15)) # Minimum 5, about 15% of square_size

    # Calculate the total dimension needed for the 3x3 grid with current sizes
    total_grid_dim = dynamic_square_size * 3 + dynamic_gap * 2

    # If the calculated total_grid_dim exceeds either image dimension, scale down.
    # This can happen if the image is very small and dynamic_square_size hit its minimum.
    if total_grid_dim > w or total_grid_dim > h:
        scale_factor_w = w / total_grid_dim if total_grid_dim > 0 else 1
        scale_factor_h = h / total_grid_dim if total_grid_dim > 0 else 1
        overall_scale_factor = min(scale_factor_w, scale_factor_h)

        dynamic_square_size = int(dynamic_square_size * overall_scale_factor)
        dynamic_gap = int(dynamic_gap * overall_scale_factor)

        # Re-apply minimums after scaling down
        dynamic_square_size = max(MIN_STICKER_SIZE_FOR_PATCH, dynamic_square_size)
        dynamic_gap = max(2, dynamic_gap) # Minimal gap can be smaller

    # Final check: if the square size is still too small after adjustments, raise an error
    if dynamic_square_size < MIN_STICKER_SIZE_FOR_PATCH:
        raise ValueError(
            f"Image ({w}x{h}) is too small to extract a meaningful 3x3 grid. "
            f"Smallest effective sticker size is {dynamic_square_size} (required {MIN_STICKER_SIZE_FOR_PATCH})."
        )

    total_grid_dim = dynamic_square_size * 3 + dynamic_gap * 2 # Recalculate with final sizes

    # Calculate starting points to center the grid
    start_x = (w - total_grid_dim) // 2
    start_y = (h - total_grid_dim) // 2

    # Ensure starting points are non-negative
    start_x = max(0, start_x)
    start_y = max(0, start_y)

    squares = []
    overlay = frame.copy()

    for row in range(3):
        for col in range(3):
            x = start_x + col * (dynamic_square_size + dynamic_gap)
            y = start_y + row * (dynamic_square_size + dynamic_gap)

            # Ensure the square fits within image bounds
            current_square_width = min(dynamic_square_size, w - x)
            current_square_height = min(dynamic_square_size, h - y)

            if current_square_width > 0 and current_square_height > 0:
                squares.append((x, y, current_square_width, current_square_height))
                cv2.rectangle(overlay, (x, y), (x + current_square_width, y + current_square_height), (255, 255, 255), 2)
            else:
                raise ValueError(
                    "Could not calculate valid square dimensions. Image might be corrupted or extremely small."
                )

    if len(squares) != 9:
        raise ValueError(f"Expected 9 squares, but detected {len(squares)}. Check image dimensions and content.")

    return squares, overlay

def classify_hsv(hsv_pixel):
    h, s, v = [int(x) for x in hsv_pixel]
    best_color = None
    best_distance = float("inf")

    for code, (rh, rs, rv) in HSV_REFERENCES.items():
        hue_distance = min(abs(h - rh), 180 - abs(h - rh))
        distance = hue_distance * 2.0 + abs(s - rs) * 0.6 + abs(v - rv) * 0.8
        if distance < best_distance:
            best_distance = distance
            best_color = code

    confidence = max(0.0, min(1.0, 1.0 - best_distance / 180.0))
    return best_color, confidence

def detect_face(image_path):
    frame = cv2.imread(str(image_path))
    if frame is None:
        raise ValueError(f"Could not read image: {image_path}")

    squares, overlay = sample_grid(frame)
    hsv = cv2.cvtColor(frame, cv2.COLOR_BGR2HSV)

    stickers = []
    confidences = []

    # Margin for patch extraction inside a detected square
    margin = 8

    for x, y, width, height in squares:
        # Ensure the patch is valid after applying margin
        patch_x_start = x + margin
        patch_y_start = y + margin
        patch_x_end = x + width - margin
        patch_y_end = y + height - margin

        # Check if the patch dimensions are valid (at least 1x1)
        if patch_x_end <= patch_x_start or patch_y_end <= patch_y_start:
            # This case should ideally be caught by MIN_STICKER_SIZE_FOR_PATCH check in sample_grid,
            # but it's a final safeguard.
            raise ValueError(f"Patch extraction failed for {image_path}: Sticker too small after margin. "
                             f"Effective patch region: ({patch_x_start},{patch_y_start}) to ({patch_x_end},{patch_y_end})")

        patch = hsv[patch_y_start:patch_y_end, patch_x_start:patch_x_end]
        if patch.size == 0:
            # This check is technically redundant if the dimension checks above pass for 1x1 patch,
            # but robustly checks against other potential reasons for empty patch.
            raise ValueError(f"Patch extraction failed for {image_path}. Empty patch detected.")

        mean_pixel = patch.reshape(-1, 3).mean(axis=0)
        code, confidence = classify_hsv(mean_pixel)
        stickers.append(code)
        confidences.append(confidence)

        cv2.putText(
            overlay, code, (x + 15, y + 35),
            cv2.FONT_HERSHEY_SIMPLEX, 0.9, (0, 255, 0), 2, cv2.LINE_AA
        )

    return stickers, confidences, overlay

def render_face_preview(stickers, size=180):
    cell = size // 3
    canvas = np.full((size, size, 3), 30, dtype=np.uint8)
    for i, code in enumerate(stickers):
        row, col = divmod(i, 3)
        x0, y0 = col * cell, row * cell
        cv2.rectangle(canvas, (x0, y0), (x0 + cell, y0 + cell), BGR_SWATCH[code], -1)
        cv2.rectangle(canvas, (x0, y0), (x0 + cell, y0 + cell), (20, 20, 20), 2)
        cv2.putText(
            canvas, code, (x0 + cell // 3, y0 + cell // 2),
            cv2.FONT_HERSHEY_SIMPLEX, 0.8, (0, 0, 0), 2, cv2.LINE_AA
        )
    return canvas

def sticker_confidence_penalty(confidences):
    if not confidences:
        return 100.0
    return sum(max(0.0, 0.8 - c) for c in confidences)

def validate_facelets(facelets):
    errors = []
    counts = Counter(c for stickers in facelets.values() for c in stickers)
    for c in "URFDLB":
        if counts.get(c, 0) != 9:
            errors.append(f"{c} appears {counts.get(c, 0)} times instead of 9.")
    centers = {face: stickers[4] for face, stickers in facelets.items()}
    if len(set(centers.values())) != 6:
        errors.append("All 6 center stickers must map to different faces.")
    return errors

def face_map_to_kociemba_string(face_map):
    values = []
    for face in FACE_ORDER:
        for code in face_map[face]:
            values.append(code)
    return "".join(values)

def explain_move(move):
    if move.endswith("2"):
        return f"Turn {move[0]} face 180 degrees"
    if move.endswith("'"):
        return f"Turn {move[0]} face counterclockwise"
    return f"Turn {move[0]} face clockwise"

